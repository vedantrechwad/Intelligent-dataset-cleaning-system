"""
cleaner/exporter.py
Reusable Standalone Python Script Exporter:
Generates an executable, production-ready Python script that applies
approved cleaning rules using pure pandas and standard library.
Zero dependencies on Streamlit, Ollama, or external ML packages.
"""

from typing import List, Dict, Any, Optional
from cleaner.rules.base import Proposal, RULE_ORDER_MAP


def generate_cleaning_script(
    approved_proposals: List[Proposal],
    original_filename: str = "dataset.csv"
) -> str:
    """
    Generate self-contained Python script code reproducing approved cleaning rules.
    """
    sorted_proposals = sorted(approved_proposals, key=lambda p: p.order_rank)

    lines = [
        "#!/usr/bin/env python3",
        '"""',
        f"Automated Data Cleaning Pipeline for '{original_filename}'",
        f"Generated by Intelligent Dataset Cleaning System",
        f"Rules Approved: {len(sorted_proposals)}",
        'Motto: Fix what can be proven, flag what can\'t.',
        '"""',
        "",
        "import argparse",
        "import os",
        "import re",
        "import pandas as pd",
        "",
        "",
        "def clean_dataset(input_path: str, output_path: str) -> pd.DataFrame:",
        "    print(f'Loading {input_path} strictly as strings...')",
        "    df = pd.read_csv(input_path, dtype=str, keep_default_na=False)",
        "    initial_shape = df.shape",
        "    print(f'Initial Shape: {initial_shape[0]} rows, {initial_shape[1]} columns')",
        ""
    ]

    has_cell_changes = False
    rule_code_blocks = []

    for prop in sorted_proposals:
        if prop.tier == "FLAG":
            continue

        prop_id = prop.id
        prop_kind = prop.kind
        desc = prop.description.replace('"', '\\"')

        rule_lines = [
            f"    # ----------------------------------------------------------------",
            f"    # Rule: {prop_id} ({prop_kind})",
            f"    # Description: {desc}",
            f"    # ----------------------------------------------------------------"
        ]

        if prop_kind == "R8_exact_duplicates":
            rule_lines.extend([
                "    dup_count = df.duplicated(keep='first').sum()",
                "    if dup_count > 0:",
                "        df = df.drop_duplicates(keep='first').reset_index(drop=True)",
                f"        print(f'[{prop_id}] Dropped {{dup_count}} exact duplicate rows')",
                ""
            ])
            rule_code_blocks.append("\n".join(rule_lines))
            continue

        # Cell-level changes
        if prop.changes:
            has_cell_changes = True
            # Group changes by column
            col_changes: Dict[str, Dict[str, str]] = {}
            for c in prop.changes:
                if c.column not in col_changes:
                    col_changes[c.column] = {}
                col_changes[c.column][c.old_value] = c.new_value

            for col, mapping in col_changes.items():
                # If mapping has <= 10 replacements, emit direct dict replace
                if len(mapping) <= 15:
                    mapping_repr = repr(mapping)
                    rule_lines.extend([
                        f"    if '{col}' in df.columns:",
                        f"        _map_{col} = {mapping_repr}",
                        f"        _mask = df['{col}'].isin(_map_{col}.keys())",
                        f"        _n_changed = _mask.sum()",
                        f"        df['{col}'] = df['{col}'].replace(_map_{col})",
                        f"        print(f'[{prop_id}] Modified {{_n_changed}} cells in column \\'{col}\\'')",
                        ""
                    ])
                else:
                    # Generic batch replacement
                    rule_lines.extend([
                        f"    if '{col}' in df.columns:",
                        f"        _map_{col} = {repr(mapping)}",
                        f"        _mask = df['{col}'].isin(_map_{col}.keys())",
                        f"        _n_changed = _mask.sum()",
                        f"        df['{col}'] = df['{col}'].map(lambda x: _map_{col}.get(x, x))",
                        f"        print(f'[{prop_id}] Modified {{_n_changed}} cells in column \\'{col}\\'')",
                        ""
                    ])
            rule_code_blocks.append("\n".join(rule_lines))

    lines.extend(rule_code_blocks)

    lines.extend([
        "    final_shape = df.shape",
        "    print(f'Final Shape: {final_shape[0]} rows, {final_shape[1]} columns')",
        "    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)",
        "    df.to_csv(output_path, index=False, encoding='utf-8')",
        "    print(f'Saved cleaned dataset to: {output_path}')",
        "    return df",
        "",
        "",
        "if __name__ == '__main__':",
        "    parser = argparse.ArgumentParser(description='Execute deterministic cleaning pipeline.')",
        "    parser.add_argument('input_file', help='Path to raw/dirty CSV file')",
        "    parser.add_argument('-o', '--output', default='cleaned_output.csv', help='Path to destination cleaned CSV')",
        "    args = parser.parse_args()",
        "",
        "    clean_dataset(args.input_file, args.output)",
        ""
    ])

    return "\n".join(lines)
